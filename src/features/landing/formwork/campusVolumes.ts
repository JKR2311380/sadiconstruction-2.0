type Draft = Omit<Volume, "reveal">

function revealFor(vol: Draft): Reveal {
  if (vol.m === "b") return 0
  if (vol.m === "p") return 6
  if (vol.m === "c") return 4
  if (vol.m === "o") return vol.g === "fg" ? 5 : 3
  if (vol.g === "fg") return 1
  if (vol.g === "mg") return 2
  return 5
}

