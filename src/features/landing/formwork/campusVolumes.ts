export type Mat = "w" | "o" | "c" | "b" | "p"
export type Layer = "fg" | "mg" | "bg"
export type Reveal = 0 | 1 | 2 | 3 | 4 | 5 | 6

/** Box: x,z = plan centre, y = soffit (bottom). 1 grid = 1 unit. */
export type Volume = {
  g: Layer
  m: Mat
  reveal: Reveal
  w: number
  h: number
  d: number
  x: number
  y: number
  z: number
}

const PY = 1.38
